// The forbidigo rule in .golangci.yml refuses a request built by hand, which is
// the only way this provider could reach an operation outside the public set
// the generated client holds. Lint enforces it, so a few edits would quietly
// undo it: a nolint directive on the offending line, a wider exemption or a
// changed pattern in the configuration, or a generated-code header on a file.
// This test makes each of those a failing test as well as a visible diff.
//
// It reads .golangci.yml as YAML, so a reordered rule, a rule naming forbidigo
// beside other linters, a rule naming no linter at all, or a global exclusion
// path is seen the same as the plain spelling.

// The exclusion rules that reach forbidigo, exactly as wantRule spells them.
// A rule reaches it when its linters list names forbidigo or it has no linters
// list at all. Changing one means changing this list too, in the same pull
// request.
var wantRequestRuleExemptions = []string{
	`linters=[forbidigo] path=(_test\.go$|^internal/provider/transport\.go$)`,
	`linters=[forbidigo] path=^internal/provider/(logging|retry)\.go$ text=RoundTrip`,
	`linters=[forbidigo] path=^internal/k0rdent/auth\.go$ text=RoundTrip`,
	`linters=[forbidigo] path-except=^internal/`,
}

// The patterns the rule refuses, in order.
var wantRequestRulePatterns = []string{
	`^http\.(NewRequest|NewRequestWithContext|Get|Head|Post|PostForm|DefaultClient)$`,
	`^http\.Client\.(Do|Get|Head|Post|PostForm)$`,
	`^http\.(RoundTripper|Transport)\.RoundTrip$`,
	`^k0rdent\.HttpRequestDoer\.Do$`,
}

// golangciConfig is the part of .golangci.yml the rule depends on.
type golangciConfig struct {
	Run struct {
		RelativePathMode string `yaml:"relative-path-mode"`
	} `yaml:"run"`
	Linters struct {
		Default  string   `yaml:"default"`
		Enable   []string `yaml:"enable"`
		Disable  []string `yaml:"disable"`
		Settings struct {
			Forbidigo map[string]any `yaml:"forbidigo"`
		} `yaml:"settings"`
		Exclusions struct {
			Generated   string           `yaml:"generated"`
			Paths       []string         `yaml:"paths"`
			PathsExcept []string         `yaml:"paths-except"`
			Rules       []map[string]any `yaml:"rules"`
		} `yaml:"exclusions"`
	} `yaml:"linters"`
}

// nolintDirective matches a nolint directive and captures what follows its
// colon, if any. A bare //nolint silences every linter, forbidigo included.
var nolintDirective = regexp.MustCompile(`//\s*nolint(?::(.*))?`)

// generatedMarkers are what golangci-lint's `generated: lax` looks for in a
// file's comments, lowercased (pkg/result/processors/
// exclusion_generated_file_matcher.go in golangci-lint v2.12.2). A file whose
// comments carry one is skipped by every linter, forbidigo included.
var generatedMarkers = []string{"code generated", "do not edit", "autogenerated file", "* generated by: swagger codegen "}

// generatedClientFiles are the only files under internal/ that may carry a
// generated-code header: the client `go generate ./internal/k0rdent` writes.
// `make client-check` fails when one differs from what the spec generates.
var generatedClientFiles = map[string]bool{
	"internal/k0rdent/client.gen.go":   true,
	"internal/k0rdent/contract.gen.go": true,
	"internal/k0rdent/limits.gen.go":   true,
	"internal/k0rdent/types.gen.go":    true,
}

func generatedClientFile(rel string) bool { return generatedClientFiles[rel] }

func TestNothingWidensTheHandBuiltRequestRule(t *testing.T) {
	root := filepath.Join("..", "..")

	t.Run("no nolint directive can silence it", func(t *testing.T) {
		var offenders []string
		err := filepath.WalkDir(filepath.Join(root, "internal"), func(path string, d os.DirEntry, err error) error {
			// Test files are outside the rule already, so a directive in one
			// silences nothing it guards.
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return err
			}
			raw, err := os.ReadFile(path) //nolint:gosec // paths come from walking the repository
			if err != nil {
				return err
			}
			for i, line := range strings.Split(string(raw), "\n") {
				if why := silencesRequestRule(line); why != "" {
					rel, err := filepath.Rel(root, path)
					if err != nil {
						return err
					}
					offenders = append(offenders, rel+":"+strconv.Itoa(i+1)+": "+why)
				}
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		if len(offenders) > 0 {
			t.Errorf("a nolint directive would silence the hand-built request rule:\n  %s",
				strings.Join(offenders, "\n  "))
		}
	})

	t.Run("no file under internal/ passes for generated code", func(t *testing.T) {
		var offenders []string
		err := filepath.WalkDir(filepath.Join(root, "internal"), func(path string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return err
			}
			marker, err := generatedMarker(path)
			if err != nil {
				return err
			}
			if marker != "" {
				rel, err := filepath.Rel(root, path)
				if err != nil {
					return err
				}
				if generatedClientFile(filepath.ToSlash(rel)) {
					return nil
				}
				offenders = append(offenders, rel+": a comment says "+strconv.Quote(marker))
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		if len(offenders) > 0 {
			t.Errorf("golangci-lint would skip these as generated, so forbidigo wouldn't check them:\n  %s",
				strings.Join(offenders, "\n  "))
		}
	})

	raw, err := os.ReadFile(filepath.Join(root, ".golangci.yml"))
	if err != nil {
		t.Fatal(err)
	}
	var cfg golangciConfig
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		t.Fatalf(".golangci.yml doesn't parse: %v", err)
	}

	t.Run("it is still on, with every pattern", func(t *testing.T) {
		if !slices.Contains(cfg.Linters.Enable, "forbidigo") {
			t.Error(".golangci.yml no longer enables forbidigo")
		}
		if slices.Contains(cfg.Linters.Disable, "forbidigo") {
			t.Error(".golangci.yml disables forbidigo")
		}
		f := cfg.Linters.Settings.Forbidigo
		if f["analyze-types"] != true {
			t.Errorf("forbidigo analyze-types is %v, want true, or an import alias gets past it", f["analyze-types"])
		}
		for key := range f {
			if key != "analyze-types" && key != "forbid" {
				t.Errorf("forbidigo has a setting this test doesn't know: %s", key)
			}
		}
		got, err := forbidPatterns(f["forbid"])
		if err != nil {
			t.Fatal(err)
		}
		if !slices.Equal(got, wantRequestRulePatterns) {
			t.Errorf("forbidigo patterns changed:\n got  %q\n want %q", got, wantRequestRulePatterns)
		}
	})

	t.Run("its exemptions are exactly the agreed ones", func(t *testing.T) {
		ex := cfg.Linters.Exclusions
		if len(ex.Paths) > 0 || len(ex.PathsExcept) > 0 {
			t.Errorf("exclusions.paths %q and paths-except %q take files away from every linter, forbidigo included",
				ex.Paths, ex.PathsExcept)
		}
		if ex.Generated != "lax" {
			t.Errorf("exclusions.generated is %q, and the generated-file guard above is written for lax", ex.Generated)
		}
		if m := cfg.Run.RelativePathMode; m != "" {
			t.Errorf("run.relative-path-mode is %q, which moves what the exemption paths match", m)
		}
		got, err := forbidigoExemptions(ex.Rules)
		if err != nil {
			t.Fatal(err)
		}
		if !slices.Equal(got, wantRequestRuleExemptions) {
			t.Errorf("exclusion rules reaching forbidigo in .golangci.yml changed:\n got  %q\n want %q\n"+
				"Widening one lets the provider build a request by hand. If the change is "+
				"intended, update wantRequestRuleExemptions in the same pull request so a "+
				"reviewer sees both.", got, wantRequestRuleExemptions)
		}
	})
}

// golangci-lint trims and lowercases each name in a nolint list
// (pkg/result/processors/nolint_filter.go in v2.12.2), so a space after a
// comma or a capital letter still silences forbidigo, and the guard has to
// read the list the same way.
func TestTheNolintGuardReadsTheListAsGolangciLintDoes(t *testing.T) {
	for line, silences := range map[string]bool{
		"x() //nolint":                              true,
		"x() // nolint:forbidigo":                   true,
		"x() //nolint:gosec,forbidigo // why":       true,
		"x() //nolint:gosec, forbidigo // why":      true,
		"x() //nolint:gosec ,  forbidigo":           true,
		"x() //nolint:Forbidigo":                    true,
		"x() //nolint:ALL":                          true,
		"x() //nolint:gosec // forbidigo is fine":   false,
		"x() //nolint:gosec, staticcheck // reason": false,
		"x() // a plain comment":                    false,
	} {
		if got := silencesRequestRule(line) != ""; got != silences {
			t.Errorf("silencesRequestRule(%q) silences = %t, want %t", line, got, silences)
		}
	}
}

// silencesRequestRule says why a line's nolint directive would silence
// forbidigo, or "" when it wouldn't.
func silencesRequestRule(line string) string {
	m := nolintDirective.FindStringSubmatch(line)
	if m == nil {
		return ""
	}
	if m[1] == "" {
		return "a bare //nolint silences every linter"
	}
	// As golangci-lint reads it: the list ends at the next comment, and each
	// name is trimmed and lowercased.
	list, _, _ := strings.Cut(m[1], "//")
	for _, item := range strings.Split(list, ",") {
		if name := strings.ToLower(strings.TrimSpace(item)); name == "forbidigo" || name == "all" {
			return "//nolint:" + strings.TrimSpace(list) + " names " + name
		}
	}
	return ""
}

// generatedMarker returns the marker that makes golangci-lint's lax mode
// treat path as generated, or "". It reads the comments up to the package
// clause, as golangci-lint does.
func generatedMarker(path string) (string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.PackageClauseOnly|parser.ParseComments)
	if err != nil {
		return "", err
	}
	var doc []string
	for _, c := range file.Comments {
		doc = append(doc, strings.TrimSpace(c.Text()))
	}
	text := strings.ToLower(strings.Join(doc, "\n"))
	for _, m := range generatedMarkers {
		if strings.Contains(text, m) {
			return m, nil
		}
	}
	return "", nil
}

// forbidPatterns lists each forbid entry's pattern, in order. An entry may be
// a bare string or a map with a pattern, and anything else is refused, so a
// `pkg:` qualifier can't narrow a pattern unseen.
func forbidPatterns(forbid any) ([]string, error) {
	list, ok := forbid.([]any)
	if !ok {
		return nil, fmt.Errorf("forbidigo forbid is %T, not a list", forbid)
	}
	var out []string
	for _, entry := range list {
		switch e := entry.(type) {
		case string:
			out = append(out, e)
		case map[string]any:
			for key := range e {
				if key != "pattern" && key != "msg" {
					return nil, fmt.Errorf("a forbid entry has %q, which this test doesn't know", key)
				}
			}
			p, ok := e["pattern"].(string)
			if !ok {
				return nil, fmt.Errorf("a forbid entry's pattern is %T, not a string", e["pattern"])
			}
			out = append(out, p)
		default:
			return nil, fmt.Errorf("a forbid entry is %T", entry)
		}
	}
	return out, nil
}

// forbidigoExemptions spells each exclusion rule that reaches forbidigo as its
// keys in sorted order, linters sorted too, so a rule reads the same however
// its YAML is ordered. A rule reaches forbidigo when it names it or names no
// linter at all.
func forbidigoExemptions(rules []map[string]any) ([]string, error) {
	var out []string
	for _, rule := range rules {
		var linters []string
		if raw, ok := rule["linters"]; ok {
			list, ok := raw.([]any)
			if !ok {
				return nil, fmt.Errorf("an exclusion rule's linters is %T, not a list", raw)
			}
			for _, l := range list {
				linters = append(linters, fmt.Sprint(l))
			}
		}
		if len(linters) > 0 && !slices.Contains(linters, "forbidigo") {
			continue
		}
		slices.Sort(linters)
		parts := []string{"linters=[" + strings.Join(linters, ",") + "]"}
		keys := make([]string, 0, len(rule))
		for key := range rule {
			if key != "linters" {
				keys = append(keys, key)
			}
		}
		slices.Sort(keys)
		for _, key := range keys {
			parts = append(parts, key+"="+fmt.Sprint(rule[key]))
		}
		out = append(out, strings.Join(parts, " "))
	}
	return out, nil
}
